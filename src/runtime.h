#pragma once

#include <Arduino.h>
#include <freertos/FreeRTOS.h>
#include <freertos/queue.h>
#include <freertos/task.h>
#include "app_ids.h"

/**
 * Runtime message pump for UI and system events.
 *
 * The runtime task owns the display state and serializes work that is triggered
 * from app code, button inputs, or the power menu. Messages are forwarded to the
 * FreeRTOS queue and processed on the runtime UI task.
 */

enum class RuntimeUiMessageType : uint8_t
{
    /** A physical button transitioned to a pressed state. */
    ButtonPressed,
    /** A button was observed as held down while repeating input. */
    ButtonDown,
    /** A physical button returned to its released state. */
    ButtonReleased,
    /** Refresh the main screen time display. */
    RefreshMainTime,
    /** Request that a specific app be opened. */
    OpenApp,
    /** Close the currently active app. */
    CloseActiveApp,
    /** Update the currently highlighted power setting. */
    UpdatePowerSelection,
    /** Refresh Task Manager resource charts. */
    UpdateTaskManagerGraphs,
    /** Transition the device into sleep mode. */
    EnterSleep
};

/**
 * Generic message payload for runtime-task communication.
 */
struct RuntimeUiMessage
{
    RuntimeUiMessageType type;
    uint8_t value;
};

/** Starts the FreeRTOS tasks that own runtime UI and app lifecycle behavior. */
bool startRuntimeTasks();
/** Sends a UI/system event to the runtime message queue. */
bool postRuntimeUiMessage(RuntimeUiMessageType type, uint8_t value = 0);
/** Queues a button event generated by a physical input pin. */
bool postButtonEvent(uint8_t pin, bool pressed);
/** Queues a repeat event for a button currently held down. */
bool postButtonDownEvent(uint8_t pin);
/** Requests that the runtime open an app identified by appId. */
bool enqueueAppOpen(uint8_t appId);
/** Requests that the runtime close the currently active app. */
bool enqueueActiveAppClose();
/** Sends app input to the active app or runtime handler. */
bool postAppInput(int8_t input);
/** Enables or disables the main menu state in the UI. */
void setMainMenuActive(bool active);
/** Returns whether the main menu is currently active. */
bool isMainMenuActive();
/** Returns true when the current task context is the runtime UI task. */
bool isRuntimeUiTask();
/** Cleans up the app lifecycle after an app finishes or is closed. */
void finishAppExecution(uint8_t appId);
/** Switches the UI to the power-screen display state. */
void activatePowerScreenUI();
/** Restores the main screen UI after leaving the power menu. */
void restoreMainScreenUI();
/** Updates the highlighted item in the power-selection UI. */
void setPowerSelectionUI(uint8_t selection);
/** Clears cached power-menu state before reopening the menu. */
void resetPowerMenuState();
/** Handles power-menu navigation input, such as up/down/confirm changes. */
void processPowerMenuInput(int8_t direction);
